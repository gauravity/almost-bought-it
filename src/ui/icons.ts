export type IconName = keyof typeof ICONS;

export const TIMER_RING_CIRCUMFERENCE = 2 * Math.PI * 6;

export function circularTimerSvg(progress: number, color: string): string {
  const clamped = Math.max(0, Math.min(1, progress));
  const offset = (TIMER_RING_CIRCUMFERENCE * (1 - clamped)).toFixed(2);
  const cStr = TIMER_RING_CIRCUMFERENCE.toFixed(2);
  return `<svg viewBox="0 0 16 16" width="16" height="16" class="timer-ring-svg" aria-hidden="true"><circle cx="8" cy="8" r="6" fill="none" stroke="rgba(255,255,255,0.18)" stroke-width="2.2"/><circle cx="8" cy="8" r="6" fill="none" stroke="${color}" stroke-width="2.2" stroke-linecap="butt" transform="rotate(-90 8 8)" stroke-dasharray="${cStr}" stroke-dashoffset="${offset}" data-timer-ring="true"/></svg>`;
}

export function updateCircularTimerRing(ringEl: Element, progress: number): void {
  const clamped = Math.max(0, Math.min(1, progress));
  const offset = (TIMER_RING_CIRCUMFERENCE * (1 - clamped)).toFixed(2);
  ringEl.setAttribute('stroke-dashoffset', offset);
}
